// Bundles the lesson notes in content/study/<course>/<item-id>.md into
// lib/study/notes.generated.js, so they ship with the app (no file reads at runtime).
// Runs before every build (see "prebuild" in package.json); run it by hand after
// editing a note in development: `node scripts/study-notes.mjs`.
import fs from "node:fs";
import path from "node:path";

const root = path.join(process.cwd(), "content", "study");
const out = path.join(process.cwd(), "lib", "study", "notes.generated.js");

const notes = {};
let count = 0;
for (const course of fs.existsSync(root) ? fs.readdirSync(root).sort() : []) {
  const dir = path.join(root, course);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith(".md")) continue;
    notes[course] ??= {};
    notes[course][file.slice(0, -3)] = fs.readFileSync(path.join(dir, file), "utf8").replace(/\r\n/g, "\n").trim();
    count++;
  }
}

fs.writeFileSync(
  out,
  `// Generated by scripts/study-notes.mjs from content/study. Don't edit by hand.\n` +
    `export const STUDY_NOTES = ${JSON.stringify(notes, null, 1)};\n`,
);
console.log(`study-notes: ${count} note(s) from content/study`);
